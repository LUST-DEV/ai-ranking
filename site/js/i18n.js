/** Resolve a dotted key; falls back to English, then to the key itself. */
export function t(lang, key, vars = {}) {
  const get = (l) => key.split(".").reduce((o, k) => (o == null ? o : o[k]), STRINGS[l]);
  let value = get(lang) ?? get("en") ?? key;
  if (typeof value !== "string") return key;
  for (const [k, v] of Object.entries(vars)) value = value.replaceAll(`{${k}}`, String(v));
  return value;
}

export function flatKeys(obj, prefix = "") {
  return Object.entries(obj).flatMap(([k, v]) =>
    v && typeof v === "object" ? flatKeys(v, `${prefix}${k}.`) : [`${prefix}${k}`],
  );
}
